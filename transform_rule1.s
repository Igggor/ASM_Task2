# Преобразование по правилу 1: замена всех символов на символ из наиболее длинной подстроки одинаковых символов
# Вход: char* text в %rdi

.global transformRule1
transformRule1:
    # Пролог функции - сохраняем используемые регистры
    push %rbx       # Сохраняем rbx (будем хранить указатель на начало строки)
    push %r12       # Сохраняем r12 (максимальная длина последовательности)
    push %r13       # Сохраняем r13 (символ для замены)
    push %r14       # Сохраняем r14 (указатель на начало текущей последовательности)
    push %r15       # Сохраняем r15 (не используется, но сохраняем для выравнивания)
    
    # Инициализация переменных
    mov %rdi, %rbx            # Сохраняем указатель на начало строки в rbx
    xor %r12, %r12            # Обнуляем r12 (максимальная длина последовательности)
    xor %r13, %r13            # Обнуляем r13 (символ самой длинной последовательности)
    mov %rbx, %r14            # Указатель на начало текущей подстроки в r14
    
    # Поиск самой длинной последовательности одинаковых символов
find_longest:
    mov %r14, %rdi            # Начинаем проверку с текущей позиции (r14)
    xor %rcx, %rcx            # Обнуляем счетчик длины текущей последовательности (rcx)
    mov (%rdi), %dl           # Загружаем первый символ последовательности в dl
    
    # Цикл проверки текущей последовательности
find_loop:
    mov (%rdi), %al           # Загружаю текущий символ в al
    test %al, %al             # Проверяю, является ли символ окончанием строки?
    jz end_find               # Если конец строки, то выхожу из цикла
    
    cmp %dl, %al              # Сравниваем текущий символ с первым символом последовательности
    jne new_sequence          # Если символы разные - начинаем новую последовательность
    
    inc %rcx                  # Увеличиваем счетчик длины текущей последовательности
    jmp next_char             # Переходим к следующему символу
    
    # Обработка новой последовательности
new_sequence:
    # Сравниваем длину текущей последовательности с максимальной
    cmp %r12, %rcx
    jle not_longer            # Если текущая короче или равна - не обновляем
    
    # Обновляем данные о максимальной последовательности
    mov %rcx, %r12            # Сохраняем новую максимальную длину
    mov %dl, %r13b            # Сохраняем символ этой последовательности
    
not_longer:
    mov %al, %dl              # Начинаем новую последовательность с текущего символа
    mov %rdi, %r14            # Запоминаем начало новой последовательности
    mov $1, %rcx              # Сбрасываем счетчик длины (текущая последовательность = 1 символ)
    
next_char:
    inc %rdi                  # Переходим к следующему символу в строке
    jmp find_loop             # Продолжаем цикл
    
    # Обработка конца строки
end_find:
    # Проверяем последнюю последовательность в строке
    cmp %r12, %rcx
    jle not_last_longer       # Если не длиннее максимальной - пропускаем
    
    # Обновляем данные о максимальной последовательности
    mov %rcx, %r12            # Новая максимальная длина
    mov %dl, %r13b            # Символ этой последовательности
    
not_last_longer:
    # Если не нашли последовательностей (все символы разные)
    test %r12, %r12
    jnz replace_all           # Если нашли последовательности - заменяем
    
    # Если все символы разные - используем первый символ строки
    mov (%rbx), %r13b         # Берем первый символ строки
    mov $1, %r12              # Устанавливаем длину = 1
    
    # Замена всех символов строки на выбранный символ
replace_all:
    mov %rbx, %rdi            # Начинаем с начала строки
    
replace_loop:
    mov (%rdi), %al           # Загружаем текущий символ
    test %al, %al             # Проверяем на конец строки
    jz end_replace            # Если конец строки - завершаем
    
    mov %r13b, (%rdi)         # Заменяем символ на выбранный (r13b)
    inc %rdi                  # Переходим к следующему символу
    jmp replace_loop          # Продолжаем цикл замены
    
    # Завершение функции
end_replace:
    # Восстанавливаю измененные последние регистры
    pop %r15
    pop %r14
    pop %r13
    pop %r12
    pop %rbx
    ret