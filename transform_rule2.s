# Преобразование по правилу 2 с временным буфером
# Вход: char* text в %rdi

.global transformRule2
transformRule2:
    # Пролог функции - сохраняем используемые регистры
    push %rbx       # Сохраняем rbx (будем использовать для хранения указателя на строку)
    push %r12       # Сохраняем r12 (для текущего указателя при обработке)
    push %r13       # Сохраняем r13 (для работы с временным буфером)
    push %r14       # Сохраняем r14 (для временных вычислений)
    push %r15       # Сохраняем r15 (для хранения длины строки)

    mov %rdi, %rbx  # Сохраняем исходный указатель на строку в rbx
    
    # 1. Находим длину строки
    call strlen     # Вызываем strlen, результат (длина) в %rax
    mov %rax, %r15  # Сохраняем длину строки в r15
    
    # 2. Создаем временный буфер из звездочек:
    lea (%rbx,%rax), %r13  # Вычисляем адрес конца строки (текущий \0)
    mov $'*', (%r13)       # Заменяем терминальный \0 на *
    mov $9, %ecx           # Счетчик для 9 дополнительных звездочек
    add $1, %r13           # Переходим к следующему байту после замененного *
add_stars:
    mov $'*', (%r13)       # Записываем звездочку в текущую позицию
    inc %r13               # Переходим к следующему байту
    loop add_stars         # Повторяем цикл, пока ecx > 0
    movb $0, (%r13)        # Добавляем новый терминальный \0 после звездочек

    # 3. Обрабатываем строку с временным буфером
    mov %rbx, %r12         # Начинаем обработку с начала строки (в r12 текущий указатель)
process_loop:
    mov (%r12), %al        # Загружаем текущий символ в al
    test %al, %al          # Проверяем на нулевой байт (новый \0)
    jz restore_string      # Если дошли до конца - переходим к восстановлению
    
    # Проверяем, является ли символ цифрой
    cmp $'0', %al          # Сравниваем с '0'
    jl next_position       # Если меньше - не цифра
    cmp $'9', %al          # Сравниваем с '9'
    jg next_position       # Если больше - не цифра
    
    # Обработка цифры:
    sub $'0', %al          # Преобразуем символ цифры в число (0-9)
    mov %r12, %r14         # Копируем текущий указатель
    add %rax, %r14         # Вычисляем адрес нужного символа (текущий + цифра)
    mov (%r14), %dl        # Загружаем символ для замены
    
    # Заменяем цифру на найденный символ
    mov %dl, (%r12)        # Записываем новый символ на место цифры
    
next_position:
    inc %r12               # Переходим к следующему символу
    jmp process_loop       # Продолжаем цикл

restore_string:
    # Восстанавливаем оригинальную строку:
    lea (%rbx,%r15), %r13  # Вычисляем адрес оригинального конца строки
    mov $10, %ecx          # Нужно очистить 10 байтов (1 замененный * + 9 добавленных)
clear_stars:
    movb $0, (%r13)        # Записываем 0 в текущий байт
    inc %r13               # Переходим к следующему байту
    loop clear_stars       # Повторяем для всех 10 байтов
    
    # Восстанавливаем оригинальный \0
    lea (%rbx,%r15), %r13  # Снова получаем адрес конца строки
    movb $0, (%r13)        # Восстанавливаем терминальный ноль

end_transform:
    # Эпилог функции - восстанавливаем регистры
    pop %r15
    pop %r14
    pop %r13
    pop %r12
    pop %rbx
    ret                    # Возвращаем управление

# Вспомогательная функция для вычисления длины строки
strlen:
    mov %rdi, %rax         # Начинаем с начала строки
strlen_loop:
    cmpb $0, (%rax)        # Сравниваем текущий байт с 0
    je strlen_end          # Если ноль - достигли конца
    inc %rax               # Переходим к следующему байту
    jmp strlen_loop        # Продолжаем цикл
strlen_end:
    sub %rdi, %rax         # Вычисляем длину (текущий адрес - начальный)
    ret                    # Возвращаем длину в rax